import {
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
} from "react-native";

import { router } from "expo-router";
import { useEffect, useMemo, useState } from "react";

import { theme } from "../constants/theme";
import { useAuth } from "../context/AuthContext";

import { getAthleteData } from "../lib/athlete";
import { buildAthleteModel } from "../lib/physiology/athleteModel";

import { AthleteData } from "../types/athlete";

export default function PowerPage() {
  const { user } = useAuth();

  const [athlete, setAthlete] =
    useState<AthleteData | null>(null);

  const [isLoading, setIsLoading] =
    useState(true);

  const [error, setError] =
    useState<string | null>(null);

  useEffect(() => {
    if (!user) {
      setAthlete(null);
      setIsLoading(false);
      return;
    }

    let isMounted = true;

    async function loadPowerData() {
      try {
        setIsLoading(true);
        setError(null);

        const athleteData =
          await getAthleteData(user!.id);

        if (isMounted) {
          setAthlete(athleteData);
        }
      } catch (loadError) {
        console.error(
          "Failed to load power data:",
          loadError
        );

        if (isMounted) {
          setError(
            "Unable to load your power model."
          );
        }
      } finally {
        if (isMounted) {
          setIsLoading(false);
        }
      }
    }

    loadPowerData();

    return () => {
      isMounted = false;
    };
  }, [user]);

  const model = useMemo(() => {
    if (!athlete) {
      return null;
    }

    return buildAthleteModel(athlete);
  }, [athlete]);

  const profile = athlete?.profile;
  const powerProfile = athlete?.powerProfile;

  const firstName =
    profile?.first_name ?? "";

  const firstInitial =
    firstName.charAt(0).toUpperCase() || "A";

  /*
   * The power curve generated by athleteModel contains
   * the modeled values derived from CP + W′.
   */
  const curve = model?.powerCurve ?? [];

  /*
   * Scale bars relative to the highest modeled power
   * currently displayed.
   */
  const maxCurvePower =
    curve.length > 0
      ? Math.max(
          ...curve.map(
            (point) => point.powerWatts
          )
        )
      : 0;

  const lastUpdated =
    formatRecordedDate(
      model?.recordedAt ?? null
    );

  return (
    <View style={styles.page}>
      <ScrollView
        showsVerticalScrollIndicator={false}
        contentContainerStyle={
          styles.scrollContent
        }
      >
        <View style={styles.container}>
          {/* Header */}
          <View style={styles.header}>
            <Pressable
              onPress={() =>
                router.push("/")
              }
            >
              <Text style={styles.logo}>
                VECTOR
              </Text>
            </Pressable>

            <View style={styles.avatar}>
              <Text style={styles.avatarText}>
                {firstInitial}
              </Text>
            </View>
          </View>

          {/* Hero */}
          <View style={styles.hero}>
            <Text style={styles.eyebrow}>
              POWER PROFILE
            </Text>

            <Text style={styles.title}>
              Your performance model.
            </Text>

            <Text style={styles.subtitle}>
              A living model of your aerobic and
              anaerobic capabilities.
            </Text>
          </View>

          {error ? (
            <View style={styles.errorCard}>
              <Text style={styles.errorText}>
                {error}
              </Text>
            </View>
          ) : null}

          {/* Main metrics */}
          <View style={styles.metrics}>
            <Metric
              label="Critical Power"
              value={
                isLoading
                  ? "..."
                  : model
                    ? `${Math.round(model.cpWatts)} W`
                    : "—"
              }
              secondary={
                model
                  ? `${(
                      model.cpWatts /
                      model.inputs.weightKg
                    ).toFixed(2)} W/kg`
                  : undefined
              }
            />

            <Metric
              label="W′"
              value={
                isLoading
                  ? "..."
                  : model
                    ? `${model.wPrimeKj.toFixed(
                        1
                      )} kJ`
                    : "—"
              }
            />

            <Metric
              label="Est. VO₂max"
              value={
                isLoading
                  ? "..."
                  : model
                    ? model.vo2Max.toFixed(1)
                    : "—"
              }
            />
          </View>

          {/* Power curve */}
          <View style={styles.sectionHeader}>
            <View>
              <Text
                style={
                  styles.sectionEyebrow
                }
              >
                POWER-DURATION MODEL
              </Text>

              <Text
                style={styles.sectionTitle}
              >
                Current capabilities
              </Text>
            </View>

            <Text style={styles.period}>
              Current model
            </Text>
          </View>

          <View style={styles.chartCard}>
            {isLoading ? (
              <View
                style={
                  styles.chartMessage
                }
              >
                <Text
                  style={
                    styles.chartMessageText
                  }
                >
                  Loading power model...
                </Text>
              </View>
            ) : model && curve.length > 0 ? (
              <View style={styles.chart}>
                {curve.map((item) => {
                  const barHeight =
                    maxCurvePower > 0
                      ? Math.max(
                          20,
                          (item.powerWatts /
                            maxCurvePower) *
                            165
                        )
                      : 20;

                  return (
                    <View
                      key={
                        item.durationSeconds
                      }
                      style={
                        styles.chartColumn
                      }
                    >
                      <Text
                        style={
                          styles.powerValue
                        }
                      >
                        {Math.round(
                          item.powerWatts
                        )}
                      </Text>

                      <View
                        style={[
                          styles.bar,
                          {
                            height:
                              barHeight,
                          },
                        ]}
                      />

                      <Text
                        style={
                          styles.duration
                        }
                      >
                        {shortenDurationLabel(
                          item.label
                        )}
                      </Text>
                    </View>
                  );
                })}
              </View>
            ) : (
              <View
                style={
                  styles.chartMessage
                }
              >
                <Text
                  style={
                    styles.chartMessageTitle
                  }
                >
                  Not enough power data
                </Text>

                <Text
                  style={
                    styles.chartMessageText
                  }
                >
                  Add valid 1, 5 and
                  12-minute maximal efforts
                  to generate your model.
                </Text>
              </View>
            )}

            <View style={styles.chartFooter}>
              <View>
                <Text
                  style={
                    styles.chartFooterLabel
                  }
                >
                  MODEL
                </Text>

                <Text
                  style={
                    styles.chartFooterValue
                  }
                >
                  Morton 3-parameter
                </Text>
              </View>

              <View>
                <Text
                  style={
                    styles.chartFooterLabel
                  }
                >
                  LAST UPDATED
                </Text>

                <Text
                  style={
                    styles.chartFooterValue
                  }
                >
                  {isLoading
                    ? "..."
                    : lastUpdated}
                </Text>
              </View>
            </View>
          </View>

          {/* Model information */}
          <View style={styles.lowerGrid}>
            <View style={styles.confidenceCard}>
              <Text style={styles.cardEyebrow}>
                MODEL PARAMETERS
              </Text>

              <View style={styles.modelParameterMain}>
                <Text style={styles.parameterNumber}>
                  {isLoading
                    ? "..."
                    : model
                      ? `${Math.round(model.pMaxWatts)} W`
                      : "—"}
                </Text>

                <Text style={styles.parameterMainLabel}>
                  Estimated Pmax
                </Text>
              </View>

              <View style={styles.parameterDivider} />

              <View style={styles.parameterRow}>
                <Text style={styles.parameterLabel}>
                  Critical Power
                </Text>

                <Text style={styles.parameterValue}>
                  {model
                    ? `${Math.round(model.cpWatts)} W`
                    : "—"}
                </Text>
              </View>

              <View style={styles.parameterRow}>
                <Text style={styles.parameterLabel}>
                  W′
                </Text>

                <Text style={styles.parameterValue}>
                  {model
                    ? `${model.wPrimeKj.toFixed(1)} kJ`
                    : "—"}
                </Text>
              </View>

              <Text style={styles.cardDescription}>
                Pmax, Critical Power and W′ are the three
                parameters of your current Morton power-duration
                model.
              </Text>
            </View>

            <View style={styles.testCard}>
              <Text
                style={styles.cardEyebrow}
              >
                CURRENT INPUTS
              </Text>

              <PowerInputRow
                label="1 minute"
                value={
                  powerProfile?.one_minute_watts !=
                  null
                    ? `${powerProfile.one_minute_watts} W`
                    : "—"
                }
              />

              <PowerInputRow
                label="5 minutes"
                value={
                  powerProfile?.five_minute_watts !=
                  null
                    ? `${powerProfile.five_minute_watts} W`
                    : "—"
                }
              />

              <PowerInputRow
                label="12 minutes"
                value={
                  powerProfile?.twelve_minute_watts !=
                  null
                    ? `${powerProfile.twelve_minute_watts} W`
                    : "—"
                }
                last
              />

              <Pressable
                style={styles.editPowerButton}
                onPress={() =>
                  router.push("/profile")
                }
              >
                <Text
                  style={
                    styles.editPowerButtonText
                  }
                >
                  Edit power data
                </Text>

                <Text
                  style={
                    styles.testArrow
                  }
                >
                  →
                </Text>
              </Pressable>
            </View>
          </View>

          {/* Insight */}
          <View style={styles.insightCard}>
            <Text
              style={styles.insightEyebrow}
            >
              VECTOR MODEL
            </Text>

            <Text
              style={styles.insightTitle}
            >
              {model
                ? "Your current physiology model is ready."
                : "More power data are required."}
            </Text>

            <Text
              style={
                styles.insightDescription
              }
            >
              {model
                ? `Your current model estimates a Critical Power of ${Math.round(
                    model.cpWatts
                  )} W with ${model.wPrimeKj.toFixed(
                    1
                  )} kJ of W′. These values are derived from your recorded 1, 5 and 12-minute maximal efforts.`
                : "Once valid maximal efforts are available, Vector can calculate your Critical Power, W′ capacity and modeled power-duration relationship."}
            </Text>
          </View>
        </View>
      </ScrollView>

      <BottomNav />
    </View>
  );
}

type MetricProps = {
  label: string;
  value: string;
  secondary?: string;
};

